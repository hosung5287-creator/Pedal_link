-- 006: 코스 경유지(routes.waypoints) 컬럼 추가
--
-- 경로 만들기에서 출발 → 경유지(순서대로) → 도착으로 코스를 만들 수 있게 됐다.
-- 경로 선(bike_path)은 경유지를 거친 모양 그대로 저장되지만, 코스를 다시 불러올 때
-- 같은 경로로 다시 계산하려면 경유지 좌표가 필요해서 따로 보관한다.
--
-- 형식: [{"lat":37.5,"lng":127.0,"label":"경유지"}, ...] JSON 텍스트 (최대 100곳)
-- 기존 코스는 NULL = 경유지 없음. 여러 번 실행해도 안전하다.
-- 로컬은 ddl-auto=update 로 자동 생성되지만, VM(ddl-auto=validate)은 이 파일을 먼저 실행해야 백엔드가 뜬다.
-- ============================================================

ALTER TABLE routes ADD COLUMN IF NOT EXISTS waypoints TEXT;
