-- ============================================================
-- 014: 라이딩 종료를 눌렀는데도 남아 있던 크루 라이딩 파티 정리
--
-- 예전에는 크루 라이딩에서 [라이딩 종료]를 누르면 파티의 ride_started_at 만 지우고 파티는 열어 뒀다.
-- 그래서 크루 라이딩이 계속 "진행 중"으로 보여, 새로고침하면 라이딩 화면이 다시 뜨고
-- 같은 크루가 새 라이딩을 열 수도 없었다. 이제 크루 라이딩 파티는 라이딩 종료와 함께 끝난다(ended).
-- 이 파일은 그 전에 멈춰 둔 채 남은 크루 라이딩 파티를 끝난 것으로 바꾼다. 스키마 변경은 없고,
-- 여러 번 실행해도 안전하다.
-- ============================================================

UPDATE parties p
SET status = 'ended'
FROM crew_events e
WHERE e.party_id = p.id
  AND p.ride_started_at IS NULL
  AND p.status <> 'ended';
